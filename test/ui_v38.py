import json, sys
from playwright.sync_api import sync_playwright
fx = json.load(open('/tmp/fixtures_v38.json')); gid = fx['gid']
errors = []; passed = 0; failed = 0
SHOTS = sys.argv[1] if len(sys.argv) > 1 else None
def ok(c, msg):
    global passed, failed
    if c: passed += 1; print('  ✓', msg)
    else: failed += 1; print('  ✗ FAIL:', msg)
def emit(page, ev, data): page.evaluate("([e,d]) => window.__srv.emit(e,d)", [ev, data])
def sent(page, name): return page.evaluate("(n) => (window.__sent||[]).filter(x => x[0]===n).map(x => x[1])", name)
def shot(page, name):
    if SHOTS: page.screenshot(path=f'{SHOTS}/{name}.png')
def route_block(page):
    page.route('**/cdnjs.cloudflare.com/**', lambda r: r.abort()); page.route('**/flagcdn.com/**', lambda r: r.abort())
def title(page): return page.inner_text('#txPageTitle')

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 400, 'height': 860}, timezone_id='Africa/Lagos'); ctx.add_init_script("localStorage.setItem('q_onboarded','1')")
    page = ctx.new_page()
    page.on('pageerror', lambda e: errors.append('PAGEERROR ' + str(e)))
    page.on('response', lambda r: errors.append('HTTP404 ' + r.url) if r.status == 404 else None)
    route_block(page)
    page.clock.set_fixed_time('2026-10-22T08:15:00+01:00')
    page.goto(f'http://localhost:8099/?groupId={gid}&role=SELLER', wait_until='load'); page.wait_for_timeout(600)
    emit(page, 'init-state', fx['init']); emit(page, 'seller-account-state', fx['verified']); page.wait_for_timeout(300)

    print('\nA. Style system')
    ok(page.evaluate("() => document.documentElement.dataset.wp") == '1', 'style number 1 is the default')
    ok(page.evaluate("() => document.body.classList.contains('wp-seller')"), 'seller UI turns the wallpaper on')
    imgs = page.evaluate("""async () => Promise.all([1,2,3,4,5,6].map(n => new Promise(r => { const i = new Image(); i.onload = () => r(i.naturalWidth); i.onerror = () => r(0); i.src = '/wallpapers/wp'+n+'.webp'; })))""")
    ok(all(w > 300 for w in imgs), 'all 6 wallpapers load')

    print('\nB. Dashboard: greeting, actions, support')
    page.evaluate("() => openTxAccountView()"); page.wait_for_timeout(300)
    ok(title(page) == 'Good morning, Kwame', 'morning greeting at 08:15: ' + title(page))
    page.clock.set_fixed_time('2026-10-22T14:05:00+01:00'); page.evaluate("() => setTxAccountNav('dashboard')")
    ok(title(page) == 'Good afternoon, Kwame', 'afternoon greeting at 14:05: ' + title(page))
    page.clock.set_fixed_time('2026-10-22T19:40:00+01:00'); page.evaluate("() => setTxAccountNav('dashboard')")
    ok(title(page) == 'Good evening, Kwame', 'evening greeting at 19:40: ' + title(page))
    page.clock.set_fixed_time('2026-10-22T11:59:00+01:00'); page.evaluate("() => setTxAccountNav('dashboard')")
    ok(title(page) == 'Good morning, Kwame', 'still morning at 11:59')
    page.clock.set_fixed_time('2026-10-22T12:00:00+01:00'); page.evaluate("() => setTxAccountNav('dashboard')")
    ok(title(page) == 'Good afternoon, Kwame', 'afternoon from 12:00')
    row = page.inner_text('#txActionRow').replace('\n', ' ')
    ok(all(w in row for w in ('Send', 'Receive', 'Withdraw', 'Support')), 'dashboard has Send, Receive, Withdraw, Support: ' + row)
    ok(page.locator('#txStyleBtn').count() == 0, 'the palette button is gone from the top bar')
    ok(page.is_visible('#txSupportBtn'), 'Support button is in the top bar')
    ok(page.is_visible('#txBottomNav') and all(w in page.inner_text('#txBottomNav') for w in ('Home', 'Transfer', 'Accounts', 'Profile')), 'bottom bar: Home, Transfer, Accounts, Profile')
    shot(page, 'home_m')
    page.click('#txActionRow button:has-text("Withdraw")'); ok(page.is_visible('#txPageWithdraw'), 'Withdraw opens the withdrawal page')
    page.click('#txBottomNav [data-bn=dashboard]')
    page.click('#txActionRow button:has-text("Receive")'); ok(page.is_visible('#txPageAccounts'), 'Receive opens the account details')

    print('\nC. Account details: own currency only, nothing extra')
    emit(page, 'receiving-details', fx['notReady']); page.wait_for_timeout(150)
    t = page.inner_text('#txAccountsBody')
    ok('being prepared' in t and 'Account number' not in t and 'IBAN' not in t, 'verified but not set up yet: "being prepared", no numbers')
    shot(page, 'accounts_preparing_m')
    emit(page, 'receiving-details', fx['detailsUSD']); page.wait_for_timeout(150)
    t = page.inner_text('#txAccountsBody'); usd = dict((r[0], r[1]) for r in fx['detailsUSD']['details']['USD']['a'] + fx['detailsUSD']['details']['USD']['b'])
    ok(all(v in t for v in usd.values()), 'USD: every detail displayed in full')
    ok(page.locator('#txAccountsBody .rc-tab').count() == 0 and 'EUR' not in t and 'GBP' not in t and 'IBAN' not in t, 'USD seller sees USD only (no currency tabs, no EUR/GBP)')
    ok('Payment reference' in t and fx['detailsUSD']['accountId'] in t, 'payment reference = Account ID is shown')
    ok(page.locator('#txAccountsBody .rc-note').count() == 0 and 'intermediary' not in t.lower() and 'business days' not in t.lower(), 'the info/warning note is gone')
    ok(page.locator('#txAccountsBody button:has-text("Copy"), #txAccountsBody .fa-copy').count() == 0, 'no copy buttons')
    ok('Sample data only' not in t and 'Northvale' not in t, 'no sample label or fake bank name')
    shot(page, 'accounts_usd_m')
    page.click('#txAccountsBody .rc-eye'); ok('•' in page.inner_text('#txAccountsBody'), 'eye hides account numbers'); page.click('#txAccountsBody .rc-eye')
    emit(page, 'receiving-details', fx['detailsEUR']); page.wait_for_timeout(150); t = page.inner_text('#txAccountsBody')
    ok('IBAN' in t and 'DE89 3704 0044 0532 0130 00' in t and 'COBADEFF' in t and '$' not in page.inner_text('#txAccountsBody .rc-intro'), 'EUR seller: IBAN + BIC, euro wording')
    ok('Account number' not in t and 'ABA' not in t and 'Sort code' not in t, 'EUR seller sees no account-number / ABA / sort-code rows')
    emit(page, 'receiving-details', fx['detailsGBP']); page.wait_for_timeout(150); t = page.inner_text('#txAccountsBody')
    ok(all(w in t for w in ('Sort code', '40-12-76', 'Account number', '12345678', 'HBUKGB4B')) and 'ABA' not in t, 'GBP seller: sort code, account number, IBAN, SWIFT')
    shot(page, 'accounts_gbp_m')
    emit(page, 'seller-account-state', fx['unverified']); emit(page, 'receiving-details', fx['lockedDetails']); page.wait_for_timeout(150)
    t = page.inner_text('#txAccountsBody'); ok('Verify identity' in t and 'IBAN' not in t, 'unverified seller: locked card, no numbers')
    emit(page, 'seller-account-state', fx['verified']); emit(page, 'receiving-details', fx['detailsUSD'])

    print('\nD. Navigation and style (Profile)')
    page.click('#txBottomNav [data-bn=profile]'); ok(page.is_visible('#txPageProfile') and page.is_visible('#txProfileStyleRow'), 'Profile has the Style row')
    page.click('#txProfileStyleRow button'); page.wait_for_timeout(200)
    ok(page.is_visible('#styleModal') and page.locator('.style-opt').count() == 6, 'picker (from Profile) shows 6 styles')
    page.evaluate("() => { window.__sent = []; }"); page.click('.style-opt[data-style="3"]'); page.wait_for_timeout(120)
    ok(page.evaluate("() => document.documentElement.dataset.wp") == '3' and sent(page, 'set-my-style')[0]['style'] == '3', 'style 3 applied and saved to the account')
    page.click('#styleModal .fa-xmark')
    for nav in ('transactions', 'statements', 'forms', 'security', 'help'):
        page.evaluate(f"() => setTxAccountNav('{nav}')"); ok(page.is_visible('#txPage' + nav.capitalize()), f'existing page still works: {nav}')
    ok(page.locator('#helpOpenSupport').count() == 1, 'Help page has a "Write to Support" card')

    print('\nE. Support popup')
    page.evaluate("() => setTxAccountNav('dashboard')"); page.click('#txSupportBtn'); page.wait_for_timeout(150)
    ok(page.is_visible('#supportModal') and page.input_value('#supEmail') == fx['verified']['email'] and page.input_value('#supName') == 'Kwame Mensah', 'popup opens with name and email pre-filled')
    shot(page, 'support_m')
    page.fill('#supEmail', 'bad'); page.fill('#supMsg', 'My payment has not arrived.'); page.click('#supSend')
    ok('valid email' in page.inner_text('#supErr') and not sent(page, 'submit-support-request'), 'invalid email is refused before sending')
    page.fill('#supEmail', 'kwame@example.com'); page.fill('#supMsg', 'short'); page.click('#supSend')
    ok('detail' in page.inner_text('#supErr') and not sent(page, 'submit-support-request'), 'too-short message is refused before sending')
    page.fill('#supMsg', 'My payment from ACME has not appeared in my account.'); page.select_option('#supTopic', 'Payment issue'); page.click('#supSend')
    s = sent(page, 'submit-support-request'); ok(len(s) == 1 and s[0]['email'] == 'kwame@example.com' and s[0]['topic'] == 'Payment issue' and 'ACME' in s[0]['message'] and s[0]['groupId'] == gid, 'valid request is sent to the server with email, topic and message')
    emit(page, 'support-request-result', {'ok': True, 'ref': 'SR-1A2B3C4D'}); page.wait_for_timeout(100)
    ok('SR-1A2B3C4D' in page.inner_text('#supportBody') and 'has been sent' in page.inner_text('#supportBody'), 'seller sees a confirmation with the reference number')
    page.click('#supportBody .send-btn'); page.click('#txActionRow button:has-text("Support")'); page.wait_for_timeout(100)
    ok(page.is_visible('#supSend'), 'Support action button reopens a fresh form')
    page.fill('#supMsg', 'Second question about withdrawals please.'); page.click('#supSend'); emit(page, 'support-request-result', {'ok': False, 'error': 'You have sent several requests in the last hour.'}); page.wait_for_timeout(100)
    ok('several requests' in page.inner_text('#supErr') and page.is_enabled('#supSend'), 'a server error is shown and the form stays usable')
    page.click('#supportModal .fa-xmark')

    print('\nF. Desktop and small screens')
    page.set_viewport_size({'width': 1280, 'height': 800}); page.evaluate("() => setTxAccountNav('accounts')"); emit(page, 'receiving-details', fx['detailsUSD']); page.wait_for_timeout(250)
    box = page.evaluate("() => { const n = document.getElementById('txBottomNav').getBoundingClientRect(), m = document.querySelector('.tx-main').getBoundingClientRect(); return [n.left, n.right, n.bottom, m.left, m.right, innerHeight] }")
    ok(box[0] >= box[3] and box[1] <= box[4] + 1 and box[2] <= box[5], 'bottom bar sits inside the main area on desktop')
    ok(page.evaluate("() => document.documentElement.scrollWidth <= innerWidth"), 'no horizontal scroll on desktop')
    shot(page, 'accounts_pc')
    page.set_viewport_size({'width': 360, 'height': 700}); page.evaluate("() => setTxAccountNav('dashboard')"); page.wait_for_timeout(200)
    ok(page.evaluate("() => document.documentElement.scrollWidth <= innerWidth"), 'no horizontal scroll at 360px')
    shot(page, 'home_360')

    print('\nG. Desk (admin)')
    ap = ctx.new_page(); ap.on('pageerror', lambda e: errors.append('ADMIN PAGEERROR ' + str(e))); route_block(ap)
    ap.goto(f'http://localhost:8099/?officer=1&groupId={gid}', wait_until='load'); ap.wait_for_timeout(500)
    emit(ap, 'bank-profiles', fx['bankProfiles']); ap.wait_for_timeout(200)
    ok(ap.locator('#banksBox [data-bk]').count() == 6 + 5 + 7, 'Receiving accounts editor has every field for USD, EUR and GBP')
    ok(ap.locator('#banksBox em.ok').count() == 3 and 'REAL' in ap.inner_text('#banksBox'), 'shows each currency as configured and tells the Desk to enter real details')
    ap.evaluate("() => { window.__sent = []; }"); ap.evaluate("() => saveBankProfiles()")
    sv = sent(ap, 'admin-set-bank-profiles'); ok(len(sv) == 1 and sv[0]['profiles']['GBP']['sortCode'] == '40-12-76' and sv[0]['profiles']['EUR']['iban'].startswith('DE89'), 'save sends all three accounts')
    ap.evaluate("() => { openModal('sellerProfileModal'); document.getElementById('spBody').innerHTML = '<p>profile</p>'; }")
    emit(ap, 'seller-profile', {'groupId': gid, 'account': fx['adminProfile']['account'], 'viewer': fx['adminProfile'].get('viewer')}); ap.wait_for_timeout(250)
    ok(ap.is_visible('#spReceiving') and len(sent(ap, 'admin-get-seller-receiving')) >= 1, 'seller profile asks for and shows the receiving-account section')
    emit(ap, 'admin-seller-receiving', fx['sellerRecv']); ap.wait_for_timeout(150)
    ok(ap.locator('#spReceiving [data-sr]').count() == 6 and 'Real details only' in ap.inner_text('#spReceiving'), 'Desk can type this seller\'s own account details')
    ap.evaluate("() => { window.__sent = []; }"); ap.fill('#spReceiving [data-sr="USD.accountNumber"]', '99887766554'); ap.evaluate(f"() => saveSellerReceiving('{gid}')")
    ss = sent(ap, 'admin-set-seller-receiving'); ok(len(ss) == 1 and ss[0]['fields']['accountNumber'] == '99887766554' and ss[0]['groupId'] == gid, 'saving sends this seller\'s details')
    emit(ap, 'support-requests', {'list': [{'ref': 'SR-1A2B3C4D', 'topic': 'Payment issue', 'name': 'Kwame Mensah', 'email': 'kwame@example.com', 'message': 'My payment has not arrived', 'createdAt': '2026-10-22T08:20:00Z', 'resolved': False, 'accountId': '48213907765'}]}); ap.wait_for_timeout(150)
    ok('SR-1A2B3C4D' in ap.inner_text('#supportBox') and 'My payment has not arrived' in ap.inner_text('#supportBox') and '1 open' in ap.inner_text('#supportBox'), 'support inbox lists the request with the seller\'s message')
    ok(ap.locator('#supportBox a[href^="mailto:kwame@example.com"]').count() == 1, 'and a link to reply to the seller')

    ok(len([e for e in errors if 'PAGEERROR' in e or ('HTTP404' in e and 'api/contact' not in e)]) == 0, 'no JS errors, no missing files: ' + str(errors[:4]))
    b.close()
print(f'\nRESULT: {passed} passed, {failed} failed')
sys.exit(1 if failed else 0)
