import json, sys
from playwright.sync_api import sync_playwright
fx = json.load(open('/tmp/fixtures_v38.json')); gid = fx['gid']
errors = []; passed = 0; failed = 0
SHOTS = sys.argv[1] if len(sys.argv) > 1 else None
def ok(c, msg):
    global passed, failed
    if c: passed += 1; print('  ✓', msg)
    else: failed += 1; print('  ✗ FAIL:', msg)
def emit(page, ev, data): page.evaluate("([e,d]) => window.__srv.emit(e,d)", [ev, data])
def sent(page, name): return page.evaluate("(n) => (window.__sent||[]).filter(x => x[0]===n).map(x => x[1])", name)
def shot(page, name):
    if SHOTS: page.screenshot(path=f'{SHOTS}/{name}.png')
def route_block(page):
    page.route('**/cdnjs.cloudflare.com/**', lambda r: r.abort()); page.route('**/flagcdn.com/**', lambda r: r.abort())

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 400, 'height': 860}); ctx.add_init_script("localStorage.setItem('q_onboarded','1')")
    page = ctx.new_page()
    page.on('pageerror', lambda e: errors.append('PAGEERROR ' + str(e)))
    page.on('response', lambda r: errors.append('HTTP404 ' + r.url) if r.status == 404 else None)
    route_block(page)
    page.goto(f'http://localhost:8099/?groupId={gid}&role=SELLER', wait_until='load'); page.wait_for_timeout(600)
    emit(page, 'init-state', fx['init']); emit(page, 'seller-account-state', fx['verified']); page.wait_for_timeout(300)

    print('\nA. Style system')
    ok(page.evaluate("() => document.documentElement.dataset.wp") == '1', 'style number 1 is the default')
    ok('wp1.webp' in page.evaluate("() => getComputedStyle(document.documentElement).getPropertyValue('--wp-img')"), 'default wallpaper image is wp1')
    ok(page.evaluate("() => document.body.classList.contains('wp-seller')"), 'seller UI turns the wallpaper on')
    ok(len([m for m in sent(page, 'get-my-style')]) >= 1, 'asks the server for the seller\'s saved style')
    imgs = page.evaluate("""async () => Promise.all([1,2,3,4,5,6].map(n => new Promise(r => { const i = new Image(); i.onload = () => r([n, i.naturalWidth, 'full']); i.onerror = () => r([n, 0, 'err']); i.src = '/wallpapers/wp'+n+'.webp'; })))""")
    ok(all(w > 300 for _, w, _ in imgs), 'all 6 wallpapers load: ' + str([(n, w) for n, w, _ in imgs]))
    thumbs = page.evaluate("""async () => Promise.all([1,2,3,4,5,6].map(n => new Promise(r => { const i = new Image(); i.onload = () => r(i.naturalWidth); i.onerror = () => r(0); i.src = '/wallpapers/wp'+n+'-thumb.webp'; })))""")
    ok(all(w > 100 for w in thumbs), 'all 6 thumbnails load')

    print('\nB. Open the seller account (approved)')
    page.evaluate("() => openTxAccountView()"); page.wait_for_timeout(300)
    ok(page.is_visible('#txAccountView'), 'seller account opens')
    bg = page.evaluate("() => getComputedStyle(document.getElementById('txAccountView')).backgroundImage")
    ok('wp1.webp' in bg, 'account home uses the chosen wallpaper as its background')
    ok(page.is_visible('#txBottomNav'), 'bottom bar is visible')
    labels = page.inner_text('#txBottomNav').replace('\n', ' ')
    ok(all(w in labels for w in ('Home', 'Transfer', 'Accounts', 'Profile')), 'bottom bar has Home, Transfer, Accounts, Profile: ' + labels)
    ok(page.is_visible('#txStyleBtn'), 'style button is in the top bar')
    ok('Receive money' in page.inner_text('#txPageDashboard'), 'dashboard has a "Receive money" shortcut')
    shot(page, 'seller_home_m')

    print('\nC. Accounts page')
    emit(page, 'receiving-details', fx['details'])
    page.click('#txBottomNav [data-bn=accounts]'); page.wait_for_timeout(300)
    ok(page.is_visible('#txPageAccounts') and 'Receive money' in page.inner_text('#txPageAccounts'), 'Accounts page opens from the bottom bar')
    ok('active' in (page.get_attribute('#txBottomNav [data-bn=accounts]', 'class') or ''), 'Accounts is highlighted in the bottom bar')
    ok(page.inner_text('#txAccountsBody .rc-bal').startswith('$24,580'), 'balance shown: ' + page.inner_text('#txAccountsBody .rc-bal'))
    t = page.inner_text('#txAccountsBody')
    usd = dict((r[0], r[1]) for r in fx['details']['details']['USD']['a'] + fx['details']['details']['USD']['b'])
    ok(all(v in t for v in usd.values()), 'USD: every detail is displayed in full (name, account no., routing, SWIFT, bank, address)')
    ok(page.locator('#txAccountsBody button:has-text("Copy"), #txAccountsBody .fa-copy, #txAccountsBody [aria-label^="Copy"]').count() == 0, 'there are NO copy buttons on the account details')
    ok('•' not in t, 'nothing is masked by default')
    ok('verified' in t.lower() and 'standard' in t.lower() and 'Kwame Mensah' in t, 'hero shows tier, Verified and the holder name')
    page.click('#txAccountsBody .rc-tab:has-text("EUR")'); page.wait_for_timeout(100)
    eur = dict((r[0], r[1]) for r in fx['details']['details']['EUR']['a'] + fx['details']['details']['EUR']['b'])
    ok(eur['IBAN'] in page.inner_text('#txAccountsBody'), 'EUR tab shows the IBAN: ' + eur['IBAN'])
    page.click('#txAccountsBody .rc-tab:has-text("GBP")'); page.wait_for_timeout(100)
    gbp = dict((r[0], r[1]) for r in fx['details']['details']['GBP']['a'] + fx['details']['details']['GBP']['b'])
    ok(all(gbp[k] in page.inner_text('#txAccountsBody') for k in ('Sort code', 'Account number', 'IBAN')), 'GBP tab shows sort code, account number and IBAN')
    ok('Sample data only' in page.inner_text('#txAccountsBody'), 'sample profile is labelled until the Desk saves real details')
    shot(page, 'seller_accounts_m')
    page.click('#txAccountsBody .rc-eye'); page.wait_for_timeout(100)
    ok('•' in page.inner_text('#txAccountsBody') and 'Available' in page.inner_text('#txAccountsBody'), 'eye button hides balance and account numbers')
    page.click('#txAccountsBody .rc-eye'); ok('•' not in page.inner_text('#txAccountsBody'), 'eye button shows them again')

    print('\nD. Bottom bar navigation')
    page.click('#txBottomNav [data-bn=withdraw]'); ok(page.is_visible('#txPageWithdraw'), 'Transfer opens the withdrawal page')
    page.click('#txBottomNav [data-bn=profile]'); ok(page.is_visible('#txPageProfile'), 'Profile opens')
    ok(page.is_visible('#txProfileStyleRow'), 'Profile has a Style row')
    page.click('#txBottomNav [data-bn=dashboard]'); ok(page.is_visible('#txPageDashboard'), 'Home opens the dashboard')
    for nav in ('transactions', 'statements', 'forms', 'security', 'help'):
        page.evaluate(f"() => setTxAccountNav('{nav}')"); ok(page.is_visible('#txPage' + nav.capitalize()), f'existing page still works: {nav}')
    ok(page.locator('#txAccountView .tx-nav [data-txnav=accounts]').count() == 1, 'sidebar also lists Accounts')

    print('\nE. Style picker')
    page.click('#txStyleBtn'); page.wait_for_timeout(200)
    ok(page.is_visible('#styleModal') and page.locator('.style-opt').count() == 6, 'picker shows 6 styles')
    ok('sel' in page.get_attribute('.style-opt[data-style="1"]', 'class'), 'style 1 is selected by default')
    shot(page, 'picker_m')
    page.evaluate("() => { window.__sent = []; }")
    page.click('.style-opt[data-style="3"]'); page.wait_for_timeout(150)
    ok(page.evaluate("() => document.documentElement.dataset.wp") == '3', 'choosing style 3 applies it at once')
    ok(sent(page, 'set-my-style') and sent(page, 'set-my-style')[0]['style'] == '3', 'choice is saved to the seller account on the server')
    ok(page.evaluate("() => localStorage.getItem('q_style')") == '3', 'and remembered on this device')
    page.click('#styleModal .fa-xmark'); page.wait_for_timeout(100)
    bg = page.evaluate("() => getComputedStyle(document.getElementById('txAccountView')).backgroundImage")
    ok('wp3.webp' in bg, 'account home now shows wallpaper 3')
    ok('wp3.webp' in page.evaluate("() => getComputedStyle(document.querySelector('.chat-main')).backgroundImage"), 'the chat wall shows wallpaper 3 as well')
    shot(page, 'seller_home_style3_m')
    emit(page, 'my-style', {'style': '5'}); ok(page.evaluate("() => document.documentElement.dataset.wp") == '5', 'a style saved on another device is applied (server value wins)')
    page.reload(wait_until='load'); page.wait_for_timeout(400)
    ok(page.evaluate("() => document.documentElement.dataset.wp") == '5', 'style survives a reload')

    print('\nF. Not approved yet')
    page.evaluate("() => localStorage.setItem('q_style','1')")
    emit(page, 'init-state', fx['init']); emit(page, 'seller-account-state', fx['unverified']); emit(page, 'receiving-details', fx['lockedDetails']); page.wait_for_timeout(200)
    page.evaluate("() => { openTxAccountView(); setTxAccountNav('accounts'); }"); page.wait_for_timeout(300)
    t = page.inner_text('#txAccountsBody')
    ok('Verify identity' in t and 'Account number' not in t and 'IBAN' not in t, 'unverified seller sees a locked card and no numbers')
    shot(page, 'seller_locked_m')

    print('\nG. Desktop layout')
    page.set_viewport_size({'width': 1280, 'height': 800})
    emit(page, 'seller-account-state', fx['verified']); emit(page, 'receiving-details', fx['details']); page.wait_for_timeout(200)
    page.evaluate("() => { setTxAccountNav('accounts'); }"); page.wait_for_timeout(300)
    box = page.evaluate("() => { const n = document.getElementById('txBottomNav').getBoundingClientRect(), m = document.querySelector('.tx-main').getBoundingClientRect(); return [n.left, n.right, n.bottom, m.left, m.right, innerHeight] }")
    ok(box[0] >= box[3] and box[1] <= box[4] + 1 and box[2] <= box[5], 'bottom bar sits inside the main area on desktop: ' + str([round(x) for x in box]))
    ok(page.evaluate("() => document.documentElement.scrollWidth <= innerWidth"), 'no horizontal scroll on desktop')
    shot(page, 'seller_accounts_pc')
    page.set_viewport_size({'width': 360, 'height': 700}); page.wait_for_timeout(200)
    ok(page.evaluate("() => document.documentElement.scrollWidth <= innerWidth"), 'no horizontal scroll at 360px')

    print('\nH. Desk (admin) bank details editor')
    ap = ctx.new_page(); ap.on('pageerror', lambda e: errors.append('ADMIN PAGEERROR ' + str(e))); route_block(ap)
    ap.goto(f'http://localhost:8099/?officer=1&groupId={gid}', wait_until='load'); ap.wait_for_timeout(500)
    prof = {c: {'sample': True, 'bankName': 'N', 'bankAddress': 'A', 'swift': 'NVLBUS33', 'routing': '000111222', 'bankCode': '00000000', 'sortCode': '00-00-00', 'ibanBank': 'NVLB'} for c in ('USD', 'EUR', 'GBP')}
    emit(ap, 'bank-profiles', {'profiles': prof}); ap.wait_for_timeout(200)
    ok(ap.locator('#banksBox [data-bk]').count() == 4 + 4 + 5, 'editor has every field for USD, EUR and GBP')
    ok('sample' in ap.inner_text('#banksBox').lower(), 'editor warns that the profile is still a sample')
    ap.evaluate("() => { window.__sent = []; }"); ap.evaluate("() => saveBankProfiles()")
    s = sent(ap, 'admin-set-bank-profiles'); ok(len(s) == 1 and s[0]['profiles']['GBP']['sortCode'] == '00-00-00', 'save sends all three profiles')

    ok(len([e for e in errors if 'PAGEERROR' in e or ('HTTP404' in e and 'api/contact' not in e)]) == 0, 'no JS errors, no missing files: ' + str(errors[:4]))
    b.close()
print(f'\nRESULT: {passed} passed, {failed} failed')
sys.exit(1 if failed else 0)
