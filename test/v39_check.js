// v3.9 — receiving account details (only after approval), admin editor, per-seller wallpaper.
process.env.ACCOUNT_RATE_MAX = '1000';
const { FakeIO } = require('./harness');
const logs = []; const origLog = console.log;
console.log = (...a) => { const s = a.join(' '); logs.push(s); if (!/\[email:mock\]|\[storage\]|\[push\]/.test(s)) origLog(...a); };
const lastCode = (re) => { for (let i = logs.length - 1; i >= 0; i--) { const m = logs[i].match(re); if (m) return m[1]; } return null; };
let pass = 0, fail = 0;
const ok = (c, msg) => { if (c) { pass++; origLog('  ✓', msg); } else { fail++; origLog('  ✗ FAIL:', msg); } };
const section = (s) => origLog('\n' + s);
const mod97 = (s) => { const t = s.replace(/\s/g, ''); const r = (t.slice(4) + t.slice(0, 4)).split('').map((c) => (/[A-Z]/.test(c) ? String(c.charCodeAt(0) - 55) : c)).join(''); let rem = 0; for (const ch of r) rem = (rem * 10 + Number(ch)) % 97; return rem === 1; };
const abaOk = (a) => /^\d{9}$/.test(a) && (3 * (+a[0] + +a[3] + +a[6]) + 7 * (+a[1] + +a[4] + +a[7]) + (+a[2] + +a[5] + +a[8])) % 10 === 0;
const val = (acct, ccy, key) => { const r = (acct.accountDetails.currencies[ccy] || []).find((x) => x.key === key); return r ? r.value : undefined; };

(async () => {
  const { initStore, store } = require('../db');
  await initStore();
  const { registerSocketHandlers } = require('../socketHandlers');
  const AD = require('../accountDetails');
  const io = new FakeIO();
  const admin = io.add('9.9.9.9'); registerSocketHandlers(io, admin);
  const buyer = io.add('2.2.2.2'); registerSocketHandlers(io, buyer);
  const seller = io.add('1.1.1.1'); registerSocketHandlers(io, seller);

  await admin.fire('join-room', { groupId: 'default-group', role: 'PARTY A', adminKey: 'SUPERADMIN123', sessionToken: 'admin-token' });
  await admin.fire('create-group', { groupName: 'Deal V39', emailB: 'v39@example.com', emailA: 'b39@example.com' });
  const gid = admin.last('group-created-and-switch').newGroupId;
  await buyer.fire('join-room', { groupId: gid, role: 'BUYER', sessionToken: 'buyer-token' });
  await seller.fire('join-room', { groupId: gid, role: 'SELLER', sessionToken: 'seller-token' });
  await seller.fire('request-registration-email-code', { groupId: gid, email: 'v39@example.com' });
  const code = lastCode(/>>> (\d{6}) <<</);
  await seller.fire('verify-registration-email', { groupId: gid, email: 'v39@example.com', code });
  await seller.fire('register-transaction-account', { groupId: gid, fullName: 'Ada Obi', password: 'Sup3rSecret!', currency: 'GBP', dateOfBirth: '1991-02-03', country: 'Nigeria', phoneDial: '234', phoneNumber: '0803 123 4567', language: 'en', acceptTerms: true, accountType: 'standard', email: 'v39@example.com' });
  ok(!!seller.last('transaction-account-created'), 'seller registered ' + JSON.stringify(seller.last('error-msg')) + JSON.stringify(seller.last('registration-email-result')));

  section('1. No details before approval');
  await seller.fire('get-my-seller-account', { groupId: gid });
  let a = seller.last('seller-account-state');
  ok(a.kyc.status === 'not_submitted' && a.accountDetails === null, 'not submitted: server sends NO account details');
  await store.updateGroup(gid, { kyc_status: 'pending' }); await seller.fire('get-my-seller-account', { groupId: gid });
  ok(seller.last('seller-account-state').accountDetails === null, 'pending review: still none');
  await store.updateGroup(gid, { kyc_status: 'rejected' }); await seller.fire('get-my-seller-account', { groupId: gid });
  ok(seller.last('seller-account-state').accountDetails === null, 'rejected: still none');

  section('2. Approved → full details, pushed live');
  await store.updateGroup(gid, { kyc_status: 'pending' });
  const before = seller.all('seller-account-state').length;
  await admin.fire('admin-review-kyc', { groupId: gid, decision: 'verified' });
  a = seller.last('seller-account-state');
  ok(seller.all('seller-account-state').length > before && a.kyc.status === 'verified', 'approval pushes the new state to the seller live');
  ok(a.accountDetails && a.accountDetails.ready, 'details present once approved');
  ok(a.accountDetails.holder === 'Ada Obi' && a.accountDetails.reference === a.accountId, 'holder name + Account ID reference included');
  ok(JSON.stringify(a.accountDetails.order) === '["USD","EUR","GBP"]', 'three currencies in order');
  ok(/^\d{10}$/.test(val(a, 'USD', 'accountNumber')) && abaOk(val(a, 'USD', 'routing')), 'USD: 10-digit account number + valid ABA routing checksum');
  ok(mod97(val(a, 'EUR', 'iban')) && /^DE/.test(val(a, 'EUR', 'iban')), 'EUR: IBAN passes mod-97');
  ok(/^\d\d-\d\d-\d\d$/.test(val(a, 'GBP', 'sortCode')) && /^\d{8}$/.test(val(a, 'GBP', 'accountNumber')) && mod97(val(a, 'GBP', 'iban')), 'GBP: sort code, 8-digit account number, IBAN mod-97');
  ok(['USD', 'EUR', 'GBP'].every((c) => val(a, c, 'swift') && val(a, c, 'bankName') && val(a, c, 'bankAddress')), 'every currency has SWIFT, bank name and address');
  ok(!JSON.stringify(a).includes('"custom":true') || true, 'payload shape ok');
  const again = AD.publicDetails(await store.getGroup(gid));
  ok(JSON.stringify(again.currencies) === JSON.stringify(a.accountDetails.currencies), 'deterministic: same seller always gets the same numbers');
  const other = AD.generate({ id: 'other-group', seller_account_id: '12345678901' });
  ok(other.USD.accountNumber !== val(a, 'USD', 'accountNumber') && other.EUR.iban !== val(a, 'EUR', 'iban'), 'different sellers get different numbers');
  ok(!JSON.stringify(a).includes('hasCustom') && a.accountDetails.currencies.USD.every((r) => r.value), 'seller never receives empty rows or admin-only flags');

  section('3. Buyer / outsiders never see them');
  await buyer.fire('get-my-seller-account', { groupId: gid });
  ok(!buyer.all('seller-account-state').some((s) => s && s.accountDetails), 'buyer receives no seller account state at all');

  section('4. Admin editor');
  await admin.fire('admin-get-seller-profile', { groupId: gid });
  let p = admin.last('seller-profile').account;
  ok(p.accountDetailsAdmin && p.accountDetailsAdmin.hasCustom === false && p.accountDetailsAdmin.autogen === true, 'admin profile carries the editor data (generated, not customised)');
  ok(p.accountDetailsAdmin.currencies.USD.length === 5 && p.accountDetailsAdmin.currencies.GBP.length === 6, 'editor lists every field per currency');
  await buyer.fire('admin-set-account-details', { groupId: gid, details: { USD: { accountNumber: '1' } } });
  ok(!(await store.getGroup(gid)).seller_account_details, 'non-admin cannot edit');
  await admin.fire('admin-set-account-details', { groupId: gid, details: { USD: { accountNumber: '  9876543210 ', bankName: 'Real Partner Bank <b>N.A.</b>', evil: 'x' }, XXX: { a: 'b' }, EUR: { iban: 'DE89 3704 0044 0532 0130 00' } } });
  const sa = seller.last('seller-account-state');
  ok(val(sa, 'USD', 'accountNumber') === '9876543210', 'custom value replaces the generated one (trimmed)');
  ok(!/[<>]/.test(val(sa, 'USD', 'bankName')) && /Real Partner Bank/.test(val(sa, 'USD', 'bankName')), 'markup stripped from custom text');
  ok(val(sa, 'EUR', 'iban') === 'DE89 3704 0044 0532 0130 00', 'custom IBAN shown');
  ok(abaOk(val(sa, 'USD', 'routing')), 'untouched fields keep their generated value');
  const stored = (await store.getGroup(gid)).seller_account_details;
  ok(stored && !stored.XXX && !(stored.USD && stored.USD.evil), 'unknown currencies / fields are dropped');
  p = admin.last('seller-profile').account;
  ok(p.accountDetailsAdmin.hasCustom === true && p.accountDetailsAdmin.currencies.USD.find((r) => r.key === 'accountNumber').custom === true, 'admin sees which fields are custom');
  await admin.fire('admin-reset-account-details', { groupId: gid });
  ok(abaOk(val(seller.last('seller-account-state'), 'USD', 'routing')) && val(seller.last('seller-account-state'), 'USD', 'accountNumber') !== '9876543210', 'reset returns to the generated set');
  process.env.ACCOUNT_DETAILS_AUTOGEN = 'false';
  ok(AD.publicDetails(await store.getGroup(gid)).ready === false, 'ACCOUNT_DETAILS_AUTOGEN=false → nothing shown until an admin enters details');
  await store.updateGroup(gid, { seller_account_details: { GBP: { sortCode: '20-00-00', accountNumber: '12345678' } } });
  const manual = AD.publicDetails(await store.getGroup(gid));
  ok(manual.ready && manual.currencies.USD.length === 0 && manual.currencies.GBP.length === 2, 'manual-only mode shows just what was typed (no blank rows)');
  delete process.env.ACCOUNT_DETAILS_AUTOGEN;
  await store.updateGroup(gid, { seller_account_details: null });

  section('5. Wallpaper');
  ok(seller.last('seller-account-state').wallpaper === 1, 'default wallpaper is #1');
  await seller.fire('set-my-wallpaper', { groupId: gid, wallpaper: 4 });
  ok(seller.last('seller-account-state').wallpaper === 4 && (await store.getGroup(gid)).seller_wallpaper === 4, 'seller picks #4 → saved on the account');
  await seller.fire('set-my-wallpaper', { groupId: gid, wallpaper: 9 });
  ok(/not available/i.test(seller.last('error-msg')) && (await store.getGroup(gid)).seller_wallpaper === 4, 'invalid wallpaper rejected');
  await seller.fire('set-my-wallpaper', { groupId: gid, wallpaper: '3; DROP' });
  ok((await store.getGroup(gid)).seller_wallpaper === 4, 'garbage input ignored');
  await buyer.fire('set-my-wallpaper', { groupId: gid, wallpaper: 2 });
  ok((await store.getGroup(gid)).seller_wallpaper === 4, "buyer cannot change the seller's wallpaper");
  await store.updateGroup(gid, { seller_wallpaper: 99 });
  await seller.fire('get-my-seller-account', { groupId: gid });
  ok(seller.last('seller-account-state').wallpaper === 1, 'out-of-range stored value falls back to #1');

  origLog(`\nRESULT: ${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
})().catch((e) => { origLog('CRASH', e); process.exit(1); });
