// v3.13 server checks: reconciled ledger (deposits, fees, out), account number vs Account ID, profile photo, Summit default.
process.env.ACCOUNT_RATE_MAX = '1000';
const { FakeIO } = require('./harness');
const logs = []; const origLog = console.log;
console.log = (...a) => { const s = a.join(' '); logs.push(s); if (!/\[email:mock\]|\[storage\]|\[push\]/.test(s)) origLog(...a); };
let pass = 0, fail = 0;
const ok = (c, msg) => { if (c) { pass++; origLog('  ✓', msg); } else { fail++; origLog('  ✗ FAIL:', msg); } };
const section = (s) => origLog('\n' + s);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

(async () => {
  const { initStore, store } = require('../db'); await initStore();
  const { registerSocketHandlers } = require('../socketHandlers');
  const FH = require('../fundsHandlers'); const BD = require('../bankDetails'); const CARD = require('../cards'); const F = require('../finance');
  const io = new FakeIO();
  const admin = io.add('9.9.9.9'); registerSocketHandlers(io, admin);
  const seller = io.add('1.1.1.1'); registerSocketHandlers(io, seller);
  const seller2 = io.add('1.1.1.2'); registerSocketHandlers(io, seller2);
  await admin.fire('join-room', { groupId: 'default-group', role: 'PARTY A', adminKey: 'SUPERADMIN123', sessionToken: 'admin-token' });
  await admin.fire('create-group', { groupName: 'Deal One', emailB: 'one@example.com' }); const g1 = admin.last('group-created-and-switch').newGroupId; await sleep(15);
  await admin.fire('create-group', { groupName: 'Deal Two', emailB: 'two@example.com' }); const g2 = admin.last('group-created-and-switch').newGroupId;
  await seller.fire('join-room', { groupId: g1, role: 'SELLER', sessionToken: 's1' });
  await seller2.fire('join-room', { groupId: g2, role: 'SELLER', sessionToken: 's2' });
  const base = { seller_registered: true, seller_currency: 'USD', kyc_status: 'verified', seller_phone: '+233244123456' };
  await store.updateGroup(g1, { ...base, seller_account_id: '11100022233', seller_full_name: 'Kwame Mensah', email_b: 'one@example.com', seller_session_token: 's1' });
  await store.updateGroup(g2, { ...base, seller_account_id: '22200033344', seller_full_name: 'Ama Boateng', email_b: 'two@example.com', seller_session_token: 's2' });

  section('1. The money reconciles: deposited 100,020, card fee 20, available 100,000');
  await store.adjustBalances(g1, { available: 100020, total: 100020 });
  await store.adjustBalances(g1, { available: -20 });
  await CARD.saveCard(store, g1, { status: 'processing', fee: { usd: 20, ledger: 20, currency: 'USD', paidAt: '2026-10-22T10:00:00Z', ref: 'CF-TEST01' } });
  const g = await store.getGroup(g1);
  const L = await FH.ledgerFor(g, []);
  ok(L.totalDeposited === 100020 && L.moneyIn === 100020 && L.moneyOut === 20 && L.available === 100000, 'Total deposited 100,020.00 · Money in 100,020.00 · Money out 20.00 · Available 100,000.00');
  ok(L.fees === 20 && L.feeItems.length === 1 && L.feeItems[0].ref === 'CF-TEST01' && L.withdrawn === 0 && L.other === 0 && L.reconciles, 'the 20.00 is the card issuing fee, nothing is unexplained');
  ok(Math.round((L.moneyIn - L.moneyOut) * 100) / 100 === L.available, 'money in minus money out equals the available balance');
  await seller.fire('get-my-seller-account', { groupId: g1 });
  const st = seller.last('seller-account-state'); ok(st && st.ledger && st.ledger.moneyOut === 20 && st.ledger.available === 100000, 'the seller\'s account state carries the ledger');
  // held funds count as deposited but not as money in; a completed withdrawal is money out
  await store.adjustBalances(g1, { held: 300, total: 300 });
  const L2 = await FH.ledgerFor(await store.getGroup(g1), []);
  ok(L2.totalDeposited === 100320 && L2.held === 300 && L2.moneyIn === 100020 && L2.reconciles, 'funds held in the vault are in Total deposited, not in Money in');
  await store.adjustBalances(g1, { available: -5000 });
  const L3 = await FH.ledgerFor(await store.getGroup(g1), [{ status: 'completed', amount_ledger: 5000 }]);
  ok(L3.withdrawn === 5000 && L3.fees === 20 && L3.moneyOut === 5020 && L3.available === 95000 && L3.reconciles, 'a completed 5,000 withdrawal is Money out as Withdrawn; fees stay 20');
  await store.adjustBalances(g1, { available: -1000, pending: 1000 });
  const L4 = await FH.ledgerFor(await store.getGroup(g1), [{ status: 'completed', amount_ledger: 5000 }, { status: 'pending', amount_ledger: 1000 }]);
  ok(L4.inProgress === 1000 && L4.moneyOut === 6020 && L4.reconciles, 'a withdrawal in progress is shown as in progress and still reconciles');
  await CARD.saveCard(store, g1, { status: 'declined', fee: { usd: 20, ledger: 20, currency: 'USD', paidAt: '2026-10-22T10:00:00Z', ref: 'CF-TEST01' } });
  const L5 = await FH.ledgerFor(await store.getGroup(g1), []);
  ok(L5.fees === 0 && L5.feeItems.length === 0, 'a declined (refunded) card application is not counted as a fee');
  await CARD.saveCard(store, g1, { status: 'issued', fee: { usd: 20, ledger: 20, currency: 'USD', paidAt: '2026-10-22T10:00:00Z', ref: 'CF-TEST01' } });
  await admin.fire('admin-get-seller-ledger', { groupId: g1 });
  ok(admin.last('funds-desk-ledger').account.ledger.fees === 20, 'the Desk sees the same ledger');

  section('2. Account ID until bank details exist, then the account number');
  const snap0 = await BD.receivingSnapshot(store, await store.getGroup(g2));
  ok(snap0.ready === false && snap0.idKind === 'accountId' && snap0.idLabel === 'Account ID 22200033344', 'no bank details: the account is identified by the Account ID');
  const rec = async (gid, extra) => { await admin.fire('admin-record-incoming-funds', { groupId: gid, payerName: 'ACME Ltd', purpose: 'Invoice 42', method: 'bank_transfer', amount: 500, amountCurrency: 'USD', treatment: 'track', trackMode: 'manual', ...extra }); return admin.last('incoming-funds-recorded'); };
  const getInc = async (gid, id) => (await store.getIncomingFundsForGroup(gid)).find((x) => x.id === id);
  let r = await rec(g2, { externalRef: 'INV42 22200033344' }); let inc = await getInc(g2, r.id);
  ok(inc.meta.referenceCheck === 'matched' && inc.meta.matchedBy === 'account_id' && inc.meta.receivingAccount.idKind === 'accountId', 'without bank details a payment is matched by the Account ID');
  let sv = F.publicIncoming(inc, false, '22200033344', '+233244123456');
  ok(sv.receivedInto.idKind === 'accountId' && sv.receivedInto.idLabel === 'Account ID 22200033344', 'the seller sees "Account ID 22200033344"');
  const USD = { accountNumber: '4821907765', routing: '021000021', swift: 'CHASUS33', bankName: 'Test Bank USA', bankAddress: '1 Main Street, New York, NY 10001' };
  await admin.fire('admin-set-bank-profiles', { profiles: { USD } });
  const snap1 = await BD.receivingSnapshot(store, await store.getGroup(g2));
  ok(snap1.ready && snap1.idKind === 'accountNumber' && snap1.idLabel === 'Account number ••7765' && snap1.accountNumber === '4821907765', 'with the Desk\'s bank details, the account is identified by the account number');
  r = await rec(g2, { externalRef: 'INV42 22200033344' }); inc = await getInc(g2, r.id);
  ok(inc.meta.referenceCheck === 'matched' && inc.meta.matchedBy === 'account_id' && inc.meta.receivingAccount.idKind === 'accountNumber', 'a shared (Desk) account: the payer quotes the seller\'s Account ID, and it matches');
  sv = F.publicIncoming(inc, false, '22200033344', '+233244123456');
  ok(sv.receivedInto.idKind === 'accountNumber' && sv.receivedInto.idLabel === 'Account number ••7765' && sv.receivedInto.accountRef === 'number ••7765', 'the seller now sees "Account number ••7765"');
  const ad = F.publicIncoming(inc, true, '22200033344', '+233244123456');
  ok(ad.track.stages.find((s) => s.n === 4).checks.some((k) => k.text === 'Funds transferred to the seller account number ••7765'), 'stage 4 names the account number');
  r = await rec(g2, { externalRef: 'only the shared number 4821907765' }); inc = await getInc(g2, r.id);
  ok(inc.meta.referenceCheck === 'different', 'the Desk\'s shared account number alone does NOT identify a seller');
  await admin.fire('admin-set-seller-receiving', { groupId: g2, fields: { ...USD, accountNumber: '99887766554' } });
  r = await rec(g2, { externalRef: 'ref 99887766554' }); inc = await getInc(g2, r.id);
  ok(inc.meta.referenceCheck === 'matched' && inc.meta.matchedBy === 'account_number', 'a seller with their OWN account is matched by that account number');
  r = await rec(g2, { externalRef: 'ref 22200033344' }); inc = await getInc(g2, r.id);
  ok(inc.meta.matchedBy === 'account_id', 'the Account ID still matches for that seller');
  const m = BD.referenceMatch({ accountId: '123', ready: true, source: 'seller', accountNumber: '4821907765' }, '48-2190 7765');
  ok(m.result === 'matched' && m.by === 'account_number' && BD.referenceMatch({ accountId: '123' }, '').result === 'none' && BD.referenceMatch({ accountId: '123' }, 'xyz').result === 'different', 'the matcher ignores spaces and dashes; empty is "none"');
  ok(!('accountNumber' in (sv.receivedInto || {})), 'the full account number never travels in the seller\'s payment record');

  section('3. Profile photo');
  const JPG = 'data:image/jpeg;base64,/9j/4AAQSkZJRgABAQEASABIAAD/2wBDAAMCAgMCAgMDAwMEAwMEBQgFBQQEBQoHBwYIDAoMDAsKCwsNDhIQDQ4RDgsLEBYQERMUFRUVDA8XGBYUGBIUFRT/';
  await seller.fire('get-my-photo', { groupId: g1 });
  ok(seller.last('my-photo').photo === null, 'no photo yet');
  await seller.fire('set-my-photo', { groupId: g1, photo: JPG });
  ok(seller.last('my-photo').photo === JPG && seller.last('my-photo').saved === true, 'a cropped JPEG is saved');
  await seller.fire('get-my-photo', { groupId: g1 });
  ok(seller.last('my-photo').photo === JPG, 'it comes back on another device / reload');
  await seller2.fire('get-my-photo', { groupId: g2 });
  ok(seller2.last('my-photo').photo === null, 'each seller has their own photo');
  await seller.fire('set-my-photo', { groupId: g1, photo: 'data:text/html;base64,PHNjcmlwdD4=' });
  ok(seller.last('photo-result').ok === false, 'anything that is not a JPEG picture is refused');
  await seller.fire('set-my-photo', { groupId: g1, photo: 'data:image/jpeg;base64,/9j/' + 'A'.repeat(170000) });
  ok(seller.last('photo-result').ok === false, 'an oversized picture is refused');
  await seller2.fire('set-my-photo', { groupId: g1, photo: JPG });
  await seller.fire('get-my-photo', { groupId: g1 }); ok(seller.last('my-photo').photo === JPG && !(await store.getSetting('photo:' + g2, null)), 'a seller cannot set someone else\'s photo');
  await seller.fire('set-my-photo', { groupId: g1, photo: null });
  ok(seller.last('my-photo').photo === null, 'the photo can be removed');

  section('4. Summit is the default wallpaper');
  await seller.fire('get-my-style', { groupId: g1 });
  ok(seller.last('my-style').style === '4' && seller.last('my-style').chosen === false, 'default is Summit (4), not yet "chosen"');
  await seller.fire('set-my-style', { groupId: g1, style: '2' }); await seller.fire('get-my-style', { groupId: g1 });
  ok(seller.last('my-style').style === '2' && seller.last('my-style').chosen === true, 'a seller\'s own pick is kept');

  origLog(`\nRESULT: ${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
})().catch((e) => { origLog('CRASH', e); process.exit(1); });
