errors = []; passed = 0; failed = 0
def ok(c, msg):
    global passed, failed
    if c: passed += 1; print('  ✓', msg)
    else: failed += 1; print('  ✗ FAIL:', msg)
def replay(page, events):
    for ev, data in events: page.evaluate("([e,d]) => window.__srv.emit(e,d)", [ev, data])
def sent(page, name): return page.evaluate("(n) => (window.__sent||[]).filter(x => x[0]===n).map(x => x[1])", name)

def boot(b, w, h, mobile=False):
    ctx = b.new_context(viewport={'width': w, 'height': h}, is_mobile=mobile, has_touch=mobile, device_scale_factor=2 if mobile else 1)
    ctx.add_init_script("localStorage.setItem('q_onboarded','1')")
    page = ctx.new_page()
    page.on('pageerror', lambda e: errors.append('PAGEERROR ' + str(e)))
    page.on('response', lambda r: errors.append('HTTP404 ' + r.url) if r.status == 404 else None)
    page.on('console', lambda m: errors.append('CONSOLE ' + m.text) if m.type == 'error' and 'flagcdn' not in m.text and 'font' not in m.text.lower() and 'ERR_' not in m.text else None)
    for pat in ['**/cdnjs.cloudflare.com/**', '**/fonts.g*apis.com/**', '**/flagcdn.com/**', '**/fonts.gstatic.com/**']: page.route(pat, lambda r: r.abort())
    page.goto(f'http://localhost:8099/?groupId={gid}&role=SELLER', wait_until='domcontentloaded'); page.wait_for_timeout(500)
    return ctx, page

